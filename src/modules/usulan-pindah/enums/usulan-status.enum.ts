/**
 * Status alur Usulan Pindah Arsip Inaktif.
 *
 * Flow:
 *   DRAFT
 *     → MENUNGGU_VERIFIKASI_ATASAN
 *       → DITOLAK_ATASAN (kembali ke DRAFT jika diperbaiki)
 *       → DISETUJUI_ATASAN
 *         → MENUNGGU_VERIFIKASI_TERAKHIR
 *           → DITOLAK_VERIFIKASI_TERAKHIR (kembali ke MENUNGGU_VERIFIKASI_ATASAN)
 *           → DISETUJUI_VERIFIKASI_TERAKHIR
 *             → DIKIRIM
 *               → BERKAS_FISIK_DIPERSIAPKAN
 *                 → SELESAI
 */
