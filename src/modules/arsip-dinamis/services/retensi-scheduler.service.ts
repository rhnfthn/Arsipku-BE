import { Injectable, Logger } from '@nestjs/common';
import { Cron, CronExpression } from '@nestjs/schedule';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { Berkas, StatusBerkas } from '../../berkas/entities/berkas.entity';

/**
 * Scheduled job: auto-close berkas whose active retention period has expired.
 *
 * Runs daily at 2 AM. Finds berkas where:
 * - status = aktif (still active)
 * - tanggal_retensi_aktif_berakhir IS NOT NULL
 * - tanggal_retensi_aktif_berakhir <= today
 *
 * Transitions: aktif → closed_retensi_aktif + creates berkas_riwayat_retensi record.
 * This makes the berkas eligible for the "transfer to inaktif" feature.
 */
@Injectable()
export class RetensiSchedulerService {
  private readonly logger = new Logger(RetensiSchedulerService.name);

  constructor(
    @InjectRepository(Berkas)
    private readonly berkasRepo: Repository<Berkas>,
  ) {}

  @Cron(CronExpression.EVERY_DAY_AT_2AM)
  async autoCloseExpiredRetensi(): Promise<number> {
    this.logger.log('Cek berkas dengan masa retensi aktif habis...');
    const today = new Date().toISOString().split('T')[0];

    const expired = await this.berkasRepo
      .createQueryBuilder('b')
      .where('b.deleted_at IS NULL')
      .andWhere('b.status = :status', { status: StatusBerkas.AKTIF })
      .andWhere('b.tanggal_retensi_aktif_berakhir IS NOT NULL')
      .andWhere('b.tanggal_retensi_aktif_berakhir <= :today', { today })
      .getMany();

    if (expired.length === 0) {
      this.logger.log('Tidak ada berkas dengan retensi habis.');
      return 0;
    }

    this.logger.log(`Ditemukan ${expired.length} berkas. Auto-close...`);

    for (const berkas of expired) {
      // Update berkas status: aktif → closed_retensi_aktif
      await this.berkasRepo
        .createQueryBuilder()
        .update(Berkas)
        .set({ status: StatusBerkas.CLOSED_RETENSI_AKTIF })
        .where('id = :id', { id: berkas.id })
        .execute();

      // Create riwayat record (id auto-generated by DB DEFAULT uuid())
      await this.berkasRepo.manager.query(
        `INSERT INTO berkas_riwayat_retensi
          (berkas_id, status_sebelumnya, status_baru, tanggal_perubahan, diproses_oleh, keterangan)
         VALUES (?, ?, ?, ?, ?, ?)`,
        [
          berkas.id,
          StatusBerkas.AKTIF,
          StatusBerkas.CLOSED_RETENSI_AKTIF,
          today,
          0,
          'Auto-close: masa retensi aktif berakhir',
        ],
      );
    }

    this.logger.log(`Auto-close selesai: ${expired.length} berkas ditutup.`);
    return expired.length;
  }
}